nop
; CHECK: nop ; encoding: [0x60,0x00,0x00,0x19]
add r0,r0,r0
; CHECK: nop ; encoding: [0x60,0x00,0x00,0x19]
mov r5,r6
; CHECK: mov r5,r6 ; encoding: [0x61,0x40,0x60,0x19]
add r7,r0,r8
; CHECK: mov r7,r8 ; encoding: [0x61,0xc0,0x80,0x19]
add r0,r7,r8
; CHECK: add r0,r7,r8 ; encoding: [0x60,0x0e,0x80,0x19]
ret
; CHECK: ret ; encoding: [0xc7,0xc0,0x00,0x00]
jspci r31,#0,r0
; CHECK: ret ; encoding: [0xc7,0xc0,0x00,0x00]
b 10
; CHECK: b 10 ; encoding: [0x08,0x00,0x00,0x0a]
bra -2
; CHECK: b -2 ; encoding: [0x08,0x00,0xff,0xfe]
beq r0,r0,7
; CHECK: b 7 ; encoding: [0x08,0x00,0x00,0x07]
beqsq r0,r0,7
; CHECK: beqsq r0,r0,7 ; encoding: [0x08,0x01,0x00,0x07]
add zero,at,r2
; CHECK: add r0,r1,r2 ; encoding: [0x60,0x02,0x20,0x19]
add cb0,cb1,gp
; CHECK: add r23,r24,r28 ; encoding: [0x65,0xf1,0xc0,0x19]
add sp,fp,ra
; CHECK: add r29,r30,r31 ; encoding: [0x67,0x7d,0xf0,0x19]
ADD R1,R2,R3
; CHECK: add r1,r2,r3 ; encoding: [0x60,0x44,0x30,0x19]
Movfrs PSW,R4
