#!/usr/bin/env python3
"""Generate callconv.ll, the calling-convention execution test.

python3 gen-callconv.py > ../callconv.ll

Functions of 0 to 12 arguments of mixed types (i8 and i16 signext and
zeroext, i32, i64) fold their arguments into a 64-bit hash; main calls each
directly and through a table of function pointers, and also checks
variadic functions, struct returns (in r2:r3 and through sret), array
arguments, dynamic allocas, a frame beyond 17-bit offsets, a frame pointer
and recursion. The expected values are computed here, independently of
LLVM; main exits with the number of the first wrong result.
"""
import random

M64 = (1 << 64) - 1
rng = random.Random(3890)

TYPES = [("i8 signext", 8, True), ("i8 zeroext", 8, False),
         ("i16 signext", 16, True), ("i16 zeroext", 16, False),
         ("i32", 32, True), ("i64", 64, True)]


def ext(v, bits, signed):
    v &= (1 << bits) - 1
    if signed and v >> (bits - 1):
        v -= 1 << bits
    return v & M64


def hash_args(vals):
    h = 0
    for v in vals:
        h = ((h << 1) ^ v) & M64
    return h


def s64(v):
    v &= M64
    return v - (1 << 64) if v >> 63 else v


def s32(v):
    v &= 0xffffffff
    return v - (1 << 32) if v >> 31 else v


out = []
emit = out.append
checks = []  # (IR value, IR type, expected)

emit("""; Calling-convention execution test (docs/abi.md sections 7 and 8),
; generated by Inputs/gen-callconv.py; edit that and regenerate.
; RUN: llc -mtriple=mipsx -filetype=obj %s -o %t.o
; RUN: %mipsx-link --builtins -o %t %t.o
; RUN: %mipsx-run --expect-exit=0 %t
; RUN: llc -mtriple=mipsx -O0 -filetype=obj %s -o %t0.o
; RUN: %mipsx-link --builtins -o %t0 %t0.o
; RUN: %mipsx-run --expect-exit=0 %t0
""")

# Functions with N arguments.
funcs = []
for n in range(13):
    types = [rng.choice(TYPES) for _ in range(n)]
    ret64 = n % 2 == 0
    name = "f%d" % n
    params = ", ".join("%s %%a%d" % (t[0], i) for i, t in enumerate(types))
    emit("define %s @%s(%s) noinline {" % ("i64" if ret64 else "i32", name, params))
    emit("  %h0 = add i64 0, 0")
    for i, (t, bits, signed) in enumerate(types):
        ty = t.split()[0]
        if ty == "i64":
            emit("  %%e%d = add i64 %%a%d, 0" % (i, i))
        else:
            emit("  %%e%d = %s %s %%a%d to i64" % (i, "sext" if signed else "zext", ty, i))
        emit("  %%s%d = shl i64 %%h%d, 1" % (i, i))
        emit("  %%h%d = xor i64 %%s%d, %%e%d" % (i + 1, i, i))
    if ret64:
        emit("  ret i64 %%h%d\n}\n" % n)
    else:
        emit("  %%r = trunc i64 %%h%d to i32\n  ret i32 %%r\n}\n" % n)
    funcs.append((name, types, ret64))

emit("@fns = global [13 x ptr] [%s]\n" % ", ".join("ptr @%s" % f[0] for f in funcs))

# Variadic functions: vsum takes n i32 words; vmix takes 8 values, i64
# where bit k of the mask is set.
emit("""declare void @llvm.va_start(ptr)
declare void @llvm.va_end(ptr)

define i64 @vsum(i32 %n, ...) noinline {
entry:
  %ap = alloca ptr
  call void @llvm.va_start(ptr %ap)
  br label %loop
loop:
  %i = phi i32 [ 0, %entry ], [ %i1, %body ]
  %h = phi i64 [ 0, %entry ], [ %h1, %body ]
  %done = icmp eq i32 %i, %n
  br i1 %done, label %exit, label %body
body:
  %v = va_arg ptr %ap, i32
  %e = sext i32 %v to i64
  %s = shl i64 %h, 1
  %h1 = xor i64 %s, %e
  %i1 = add i32 %i, 1
  br label %loop
exit:
  call void @llvm.va_end(ptr %ap)
  ret i64 %h
}

define i64 @vmix(i32 %mask, ...) noinline {
entry:
  %ap = alloca ptr
  call void @llvm.va_start(ptr %ap)
  br label %loop
loop:
  %i = phi i32 [ 0, %entry ], [ %i1, %next ]
  %h = phi i64 [ 0, %entry ], [ %h1, %next ]
  %done = icmp eq i32 %i, 8
  br i1 %done, label %exit, label %body
body:
  %bit = lshr i32 %mask, %i
  %is64 = and i32 %bit, 1
  %w = icmp ne i32 %is64, 0
  br i1 %w, label %get64, label %get32
get64:
  %v64 = va_arg ptr %ap, i64
  br label %next
get32:
  %v32 = va_arg ptr %ap, i32
  %e32 = sext i32 %v32 to i64
  br label %next
next:
  %e = phi i64 [ %v64, %get64 ], [ %e32, %get32 ]
  %s = shl i64 %h, 1
  %h1 = xor i64 %s, %e
  %i1 = add i32 %i, 1
  br label %loop
exit:
  call void @llvm.va_end(ptr %ap)
  ret i64 %h
}
""")

# Structs and arrays.
emit("""define { i32, i32 } @pair(i32 %a, i32 %b) noinline {
  %s = add i32 %a, %b
  %d = sub i32 %a, %b
  %r0 = insertvalue { i32, i32 } undef, i32 %s, 0
  %r1 = insertvalue { i32, i32 } %r0, i32 %d, 1
  ret { i32, i32 } %r1
}

; Too big for r2:r3: returned through a hidden pointer in r4.
define { i32, i32, i32 } @triple(i32 %a, i32 %b) noinline {
  %x = xor i32 %a, %b
  %r0 = insertvalue { i32, i32, i32 } undef, i32 %a, 0
  %r1 = insertvalue { i32, i32, i32 } %r0, i32 %b, 1
  %r2 = insertvalue { i32, i32, i32 } %r1, i32 %x, 2
  ret { i32, i32, i32 } %r2
}

define i32 @arr(i32 %pre, [3 x i32] %a, i32 %post) noinline {
  %a0 = extractvalue [3 x i32] %a, 0
  %a1 = extractvalue [3 x i32] %a, 1
  %a2 = extractvalue [3 x i32] %a, 2
  %t0 = sub i32 %a0, %pre
  %t1 = shl i32 %a1, 1
  %t2 = xor i32 %a2, %post
  %u = add i32 %t0, %t1
  %r = add i32 %u, %t2
  ret i32 %r
}
""")

# Frames: dynamic alloca then a call with stack arguments; a big frame; a
# frame pointer; recursion.
f12 = funcs[12]
f12_vals = [rng.randrange(-100, 100) for _ in range(12)]
emit("""define i64 @dyn(i32 %n) noinline {
entry:
  %p = alloca i32, i32 %n
  br label %fill
fill:
  %i = phi i32 [ 0, %entry ], [ %i1, %fill ]
  %q = getelementptr i32, ptr %p, i32 %i
  %v3 = shl i32 %i, 2
  %v = sub i32 %v3, %i
  store volatile i32 %v, ptr %q
  %i1 = add i32 %i, 1
  %more = icmp ult i32 %i1, %n
  br i1 %more, label %fill, label %use
use:
  %last = getelementptr i32, ptr %p, i32 %n
  %lastm = getelementptr i32, ptr %last, i32 -1
  %lv = load volatile i32, ptr %lastm
  %h = call i64 @{f}({args})
  %lv64 = sext i32 %lv to i64
  %r = xor i64 %h, %lv64
  ret i64 %r
}}
""".replace("{f}", f12[0]).replace("{{", "{").replace("}}", "}").replace(
    "{args}", ", ".join("%s %d" % (t[0], v) for t, v in zip(f12[1], f12_vals))))

emit("""define i64 @big(i32 %x) noinline {{
  %a = alloca [20000 x i32]
  %p0 = getelementptr [20000 x i32], ptr %a, i32 0, i32 0
  %pe = getelementptr [20000 x i32], ptr %a, i32 0, i32 19999
  store volatile i32 %x, ptr %p0
  %y = add i32 %x, 1
  store volatile i32 %y, ptr %pe
  %h = call i64 @{f}({args})
  %v0 = load volatile i32, ptr %p0
  %ve = load volatile i32, ptr %pe
  %s = add i32 %v0, %ve
  %s64 = sext i32 %s to i64
  %r = xor i64 %h, %s64
  ret i64 %r
}}

define i32 @withfp(i32 %x) noinline "frame-pointer"="all" {{
  %a = alloca i32
  store volatile i32 %x, ptr %a
  %r = call i32 @fib(i32 %x)
  %v = load volatile i32, ptr %a
  %s = add i32 %r, %v
  ret i32 %s
}}

define i32 @fib(i32 %n) noinline {{
entry:
  %small = icmp slt i32 %n, 2
  br i1 %small, label %base, label %rec
base:
  ret i32 %n
rec:
  %n1 = sub i32 %n, 1
  %n2 = sub i32 %n, 2
  %f1 = call i32 @fib(i32 %n1)
  %f2 = call i32 @fib(i32 %n2)
  %s = add i32 %f1, %f2
  ret i32 %s
}}
""".format(f=f12[0], args=", ".join("%s %d" % (t[0], v) for t, v in zip(f12[1], f12_vals))))

h12 = hash_args([ext(v, t[1], t[2]) for t, v in zip(f12[1], f12_vals)])

# main
emit("define i32 @main() {")
for k, (name, types, ret64) in enumerate(funcs):
    vals = [rng.randrange(-(1 << (t[1] - 1)), 1 << (t[1] - 1)) if t[2]
            else rng.randrange(0, 1 << t[1]) for t in types]
    args = ", ".join("%s %d" % (t[0], v) for t, v in zip(types, vals))
    h = hash_args([ext(v, t[1], t[2]) for t, v in zip(types, vals)])
    rty = "i64" if ret64 else "i32"
    exp = s64(h) if ret64 else s32(h)
    emit("  %%d%d = call %s @%s(%s)" % (k, rty, name, args))
    checks.append(("%%d%d" % k, rty, exp))
    emit("  %%fp%d = getelementptr [13 x ptr], ptr @fns, i32 0, i32 %d" % (k, k))
    emit("  %%fn%d = load ptr, ptr %%fp%d" % (k, k))
    emit("  %%i%d = call %s %%fn%d(%s)" % (k, rty, k, args))
    checks.append(("%%i%d" % k, rty, exp))

vs = [rng.randrange(-1000, 1000) for _ in range(7)]
emit("  %%vs = call i64 (i32, ...) @vsum(i32 7, %s)" % ", ".join("i32 %d" % v for v in vs))
checks.append(("%vs", "i64", s64(hash_args([v & M64 for v in vs]))))
mask = 0b10110010
mix = []
for k in range(8):
    if mask >> k & 1:
        mix.append(("i64", rng.randrange(-(1 << 40), 1 << 40)))
    else:
        mix.append(("i32", rng.randrange(-(1 << 20), 1 << 20)))
emit("  %%vm = call i64 (i32, ...) @vmix(i32 %d, %s)" % (mask, ", ".join("%s %d" % m for m in mix)))
checks.append(("%vm", "i64", s64(hash_args([v & M64 for _, v in mix]))))
# Named arguments filling r4-r11 first, then variadic ones.
emit("  %%vf = call i64 (i32, ...) @vsum(i32 3, i32 %d, i32 %d, i32 %d)" % (11, -22, 33))
checks.append(("%vf", "i64", s64(hash_args([11, (-22) & M64, 33]))))

emit("""  %pr = call { i32, i32 } @pair(i32 100, i32 58)
  %pr0 = extractvalue { i32, i32 } %pr, 0
  %pr1 = extractvalue { i32, i32 } %pr, 1
  %tr = call { i32, i32, i32 } @triple(i32 5, i32 9)
  %tr0 = extractvalue { i32, i32, i32 } %tr, 0
  %tr1 = extractvalue { i32, i32, i32 } %tr, 1
  %tr2 = extractvalue { i32, i32, i32 } %tr, 2
  %ar = call i32 @arr(i32 7, [3 x i32] [i32 100, i32 21, i32 6], i32 3)
  %dy = call i64 @dyn(i32 37)
  %bg = call i64 @big(i32 1234)
  %wf = call i32 @withfp(i32 15)""")
checks += [("%pr0", "i32", 158), ("%pr1", "i32", 42), ("%tr0", "i32", 5),
           ("%tr1", "i32", 9), ("%tr2", "i32", 5 ^ 9),
           ("%ar", "i32", (100 - 7) + 42 + (6 ^ 3)),
           ("%dy", "i64", s64(h12 ^ (36 * 3))),
           ("%bg", "i64", s64(h12 ^ (1234 + 1235))),
           ("%wf", "i32", 610 + 15)]
emit("  br label %c1")
for k, (val, ty, exp) in enumerate(checks, start=1):
    nxt = "c%d" % (k + 1) if k < len(checks) else "pass"
    emit("c%d:\n  %%e%d = icmp ne %s %s, %d\n  br i1 %%e%d, label %%f%d, label %%%s"
         % (k, k, ty, val, exp, k, k, nxt))
    emit("f%d:\n  ret i32 %d" % (k, k))
emit("pass:\n  ret i32 0\n}")
assert len(checks) < 125
print("\n".join(out))
