#!/usr/bin/env python3
"""Generate muldiv.ll: multiply, divide, remainder and shifts over edge
values, 32 and 64 bits, run on the simulator against results computed
here.

python3 gen-muldiv.py > ../muldiv.ll

The operands are loaded from global arrays, so llc cannot fold them. Each
group of results is hashed (h = (h << 1) ^ v) and compared; main exits with
the number of the first wrong group. Division by zero and INT_MIN / -1 are
undefined in LLVM IR and left out (the SDK's own tests cover the helpers'
behaviour there).
"""
import random

rng = random.Random(1990)
M32, M64 = (1 << 32) - 1, (1 << 64) - 1


def s(v, bits):
    v &= (1 << bits) - 1
    return v - (1 << bits) if v >> (bits - 1) else v


def tdiv(a, b):
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q


def edges(bits):
    lo, hi = -(1 << (bits - 1)), (1 << (bits - 1)) - 1
    vals = {0, 1, -1, 2, -2, 3, 7, 10, -10, lo, hi, lo + 1, hi - 1,
            1 << (bits // 2), -(1 << (bits // 2)), 0x55555555, -0x12345678}
    vals |= {rng.randrange(lo, hi) for _ in range(6)}
    return sorted(v for v in vals if lo <= v <= hi)


A32 = edges(32)
B32 = [v for v in A32 if v != 0]
A64 = edges(64)
B64 = [v for v in A64 if v != 0][:12]
A64 = A64[:14]
SH = [0, 1, 2, 7, 15, 16, 30, 31]
CMUL = [3, 5, 6, 7, 9, 10, 12, 15, 17, 24, 31, 33, 100, 255, 1000, -1, -3,
        -7, -100, 0x7fffffff, 1234567, 65535]
CDIV = [1, 2, 4, 8, 16, 1 << 30, 3, 7, 10, -1, -2, -4, -8, -16, 1000]

out = []
emit = out.append
groups = []  # (name, expected hash)


def hash_add(h, v):
    return ((h << 1) ^ (v & M32)) & M32


def arr(name, vals, bits):
    emit("@%s = global [%d x i%d] [%s]" % (name, len(vals), bits,
                                           ", ".join("i%d %d" % (bits, v) for v in vals)))


emit("""; Multiply, divide, remainder and shifts over edge values (work package
; S12), generated by Inputs/gen-muldiv.py; edit that and regenerate.
; RUN: llc -mtriple=mipsx -filetype=obj %s -o %t.o
; RUN: %mipsx-link --builtins -o %t %t.o
; RUN: %mipsx-run --expect-exit=0 %t
; RUN: llc -mtriple=mipsx -O0 -filetype=obj %s -o %t0.o
; RUN: %mipsx-link --builtins -o %t0 %t0.o
; RUN: %mipsx-run --expect-exit=0 %t0
""")
arr("a32", A32, 32)
arr("b32", B32, 32)
arr("a64", A64, 64)
arr("b64", B64, 64)
arr("sh", SH, 32)
emit("")


# A loop over a (and b) applying an expression, hashing each result into h.
# body(x, y) returns IR lines computing %v (i32) from %x and %y.
def loop2(fname, n, m, abits, bbits, aname, bname, body):
    emit("define i32 @%s() noinline {" % fname)
    emit("entry:\n  br label %outer")
    emit("outer:\n  %i = phi i32 [ 0, %entry ], [ %i1, %outer.next ]")
    emit("  %h = phi i32 [ 0, %entry ], [ %hj, %outer.next ]")
    emit("  %%pa = getelementptr [%d x i%d], ptr @%s, i32 0, i32 %%i" % (n, abits, aname))
    emit("  %%x = load i%d, ptr %%pa" % abits)
    emit("  br label %inner")
    emit("inner:\n  %j = phi i32 [ 0, %outer ], [ %j1, %inner ]")
    emit("  %hh = phi i32 [ %h, %outer ], [ %h2, %inner ]")
    emit("  %%pb = getelementptr [%d x i%d], ptr @%s, i32 0, i32 %%j" % (m, bbits, bname))
    emit("  %%y = load i%d, ptr %%pb" % bbits)
    for l in body:
        emit("  " + l)
    emit("  %hs = shl i32 %hh, 1")
    emit("  %h2 = xor i32 %hs, %v")
    emit("  %j1 = add i32 %j, 1")
    emit("  %%jm = icmp ult i32 %%j1, %d" % m)
    emit("  br i1 %jm, label %inner, label %outer.next")
    emit("outer.next:\n  %hj = phi i32 [ %h2, %inner ]")
    emit("  %i1 = add i32 %i, 1")
    emit("  %%im = icmp ult i32 %%i1, %d" % n)
    emit("  br i1 %im, label %outer, label %exit")
    emit("exit:\n  ret i32 %hj\n}\n")


def expect2(xs, ys, f):
    h = 0
    for x in xs:
        for y in ys:
            h = hash_add(h, f(x, y))
    return h


ops32 = [
    ("mul", lambda x, y: x * y),
    ("udiv", lambda x, y: (x & M32) // (y & M32)),
    ("urem", lambda x, y: (x & M32) % (y & M32)),
    ("sdiv", lambda x, y: tdiv(x, y)),
    ("srem", lambda x, y: x - tdiv(x, y) * y),
]
for op, f in ops32:
    if op in ("sdiv", "srem"):
        # Skip INT_MIN / -1: select a divisor of 1 instead (and so in the
        # model).
        body = ["%isminx = icmp eq i32 %x, -2147483648",
                "%ism1 = icmp eq i32 %y, -1",
                "%bad = and i1 %isminx, %ism1",
                "%yy = select i1 %bad, i32 1, i32 %y",
                "%%v = %s i32 %%x, %%yy" % op]
        g = lambda x, y, f=f: f(x, 1 if (x == -(1 << 31) and y == -1) else y)
    else:
        body = ["%%v = %s i32 %%x, %%y" % op]
        g = f
    loop2("t32_" + op, len(A32), len(B32), 32, 32, "a32", "b32", body)
    groups.append(("t32_" + op, expect2(A32, B32, g)))

# Quotient and remainder together (one __udivsi3 call).
loop2("t32_udivrem", len(A32), len(B32), 32, 32, "a32", "b32",
      ["%q = udiv i32 %x, %y", "%r = urem i32 %x, %y", "%r3 = shl i32 %r, 3",
       "%v = xor i32 %q, %r3"])
groups.append(("t32_udivrem", expect2(A32, B32, lambda x, y: ((x & M32) // (y & M32)) ^ (((x & M32) % (y & M32)) << 3))))

# Variable shifts.
for op, f in [("shl", lambda x, k: x << k), ("lshr", lambda x, k: (x & M32) >> k),
              ("ashr", lambda x, k: x >> k)]:
    loop2("t32_" + op, len(A32), len(SH), 32, 32, "a32", "sh", ["%%v = %s i32 %%x, %%y" % op])
    groups.append(("t32_" + op, expect2(A32, SH, f)))

# Constant multipliers and divisors (single loop over a32, y unused).
for name, consts, mk, f in [
    ("cmul", CMUL, lambda c: "mul i32 %%x, %d" % c, lambda x, c: x * c),
    ("cudiv", [c for c in CDIV if c > 0], lambda c: "udiv i32 %%x, %d" % c, lambda x, c: (x & M32) // c),
    ("curem", [c for c in CDIV if c > 0], lambda c: "urem i32 %%x, %d" % c, lambda x, c: (x & M32) % c),
    ("csdiv", CDIV, lambda c: "sdiv i32 %%x, %d" % c, None),
    ("csrem", CDIV, lambda c: "srem i32 %%x, %d" % c, None)]:
    lines = []
    for k, c in enumerate(consts):
        # x is never INT_MIN when c is -1 (guarded with a select).
        if name in ("csdiv", "csrem") and c == -1:
            lines.append("%%g%d = icmp eq i32 %%x, -2147483648" % k)
            lines.append("%%xx%d = select i1 %%g%d, i32 0, i32 %%x" % (k, k))
            lines.append("%%c%d = %s" % (k, mk(c).replace("%x", "%%xx%d" % k)))
        else:
            lines.append("%%c%d = %s" % (k, mk(c)))
        lines.append("%%s%d = shl i32 %s, 1" % (k, "%y" if k == 0 else "%%t%d" % (k - 1)))
        lines.append("%%t%d = xor i32 %%s%d, %%c%d" % (k, k, k))
    lines.append("%%v = add i32 %%t%d, 0" % (len(consts) - 1))
    # Use the sh array (one element) just to share the loop shape: y = 0.
    loop2("t32_" + name, len(A32), 1, 32, 32, "a32", "sh", lines)

    def model(x, y, name=name, consts=consts):
        t = y
        for c in consts:
            if name == "cmul":
                v = x * c
            elif name == "cudiv":
                v = (x & M32) // c
            elif name == "curem":
                v = (x & M32) % c
            else:
                xx = 0 if (c == -1 and x == -(1 << 31)) else x
                q = tdiv(xx, c)
                v = q if name == "csdiv" else xx - q * c
            t = ((t << 1) ^ (v & M32)) & M32
        return t
    groups.append(("t32_" + name, expect2(A32, [0], model)))

# 64-bit: results folded to 32 bits as lo ^ hi.
def body64(expr):
    return [expr, "%vl = trunc i64 %w to i32", "%wh = lshr i64 %w, 32",
            "%vh = trunc i64 %wh to i32", "%v = xor i32 %vl, %vh"]


def fold64(v):
    v &= M64
    return (v & M32) ^ (v >> 32)


for op, f in [("mul", lambda x, y: x * y),
              ("udiv", lambda x, y: (x & M64) // (y & M64)),
              ("urem", lambda x, y: (x & M64) % (y & M64))]:
    loop2("t64_" + op, len(A64), len(B64), 64, 64, "a64", "b64",
          body64("%%w = %s i64 %%x, %%y" % op))
    groups.append(("t64_" + op, expect2(A64, B64, lambda x, y, f=f: fold64(f(x, y)))))
for op in ("sdiv", "srem"):
    lo = -(1 << 63)
    body = ["%isminx = icmp eq i64 %x, -9223372036854775808",
            "%ism1 = icmp eq i64 %y, -1", "%bad = and i1 %isminx, %ism1",
            "%yy = select i1 %bad, i64 1, i64 %y"] + body64("%%w = %s i64 %%x, %%yy" % op)
    loop2("t64_" + op, len(A64), len(B64), 64, 64, "a64", "b64", body)

    def m(x, y, op=op):
        y = 1 if (x == lo and y == -1) else y
        q = tdiv(x, y)
        return fold64(q if op == "sdiv" else x - q * y)
    groups.append(("t64_" + op, expect2(A64, B64, m)))
for op, f in [("shl", lambda x, k: x << k), ("lshr", lambda x, k: (x & M64) >> k),
              ("ashr", lambda x, k: x >> k)]:
    loop2("t64_" + op, len(A64), len(SH), 64, 32, "a64", "sh",
          body64("%%k = zext i32 %%y to i64\n  %%w = %s i64 %%x, %%k" % op))
    groups.append(("t64_" + op, expect2(A64, SH, lambda x, k, f=f: fold64(f(x, k)))))

emit("define i32 @main() {\nentry:\n  br label %c1")
for n, (fn, exp) in enumerate(groups, start=1):
    nxt = "c%d" % (n + 1) if n < len(groups) else "pass"
    emit("c%d:\n  %%r%d = call i32 @%s()\n  %%e%d = icmp ne i32 %%r%d, %d\n  br i1 %%e%d, label %%f%d, label %%%s"
         % (n, n, fn, n, n, s(exp, 32), n, n, nxt))
    emit("f%d:\n  ret i32 %d" % (n, n))
emit("pass:\n  ret i32 0\n}")
print("\n".join(out))
