#ifndef LLVM_LIB_TARGET_MIPSX_MIPSXSUBTARGET_H
#define LLVM_LIB_TARGET_MIPSX_MIPSXSUBTARGET_H

#include "MIPSXFrameLowering.h"
#include "MIPSXISelLowering.h"
#include "MIPSXInstrInfo.h"
#include "MIPSXRegisterInfo.h"
#include "llvm/CodeGen/SelectionDAGTargetInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include <memory>

#define GET_SUBTARGETINFO_HEADER
#include "MIPSXGenSubtargetInfo.inc"

namespace llvm {

class MIPSXSubtarget : public MIPSXGenSubtargetInfo {
  bool HasES3890 = false;
  bool UseLongCalls = false;

  MIPSXInstrInfo InstrInfo;
  MIPSXFrameLowering FrameLowering;
  MIPSXTargetLowering TLInfo;
  std::unique_ptr<const SelectionDAGTargetInfo> TSInfo;

  MIPSXSubtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS);

public:
  MIPSXSubtarget(const Triple &TT, StringRef CPU, StringRef FS,
                 const TargetMachine &TM);
  ~MIPSXSubtarget() override;

  // Generated by TableGen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  bool hasES3890() const { return HasES3890; }
  bool useLongCalls() const { return UseLongCalls; }

  const MIPSXInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const MIPSXFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const MIPSXRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }
  const MIPSXTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override {
    return TSInfo.get();
  }
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_MIPSX_MIPSXSUBTARGET_H
